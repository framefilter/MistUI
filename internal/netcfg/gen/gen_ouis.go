//go:build ignore

// gen_ouis.go regenerates ../oui_data.go from the IEEE MA-L registry.
//
// Run from internal/netcfg:  go run ./gen/gen_ouis.go
//
// It keeps only globally-administered unicast prefixes (real hardware —
// the locally-administered bit clear), grouped by vendor, and emits them as
// hex-string constants decoded at package init. Depth is the point: the
// wider each pool, the less a rolled identity stands out.
package main

import (
	"bufio"
	"encoding/csv"
	"fmt"
	"net/http"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

const source = "https://standards-oui.ieee.org/oui/oui.csv"

func main() {
	vendors := []struct {
		key string
		re  *regexp.Regexp
	}{
		{"apple", regexp.MustCompile(`(?i)\bApple\b`)},
		{"samsung", regexp.MustCompile(`(?i)Samsung`)},
		{"google", regexp.MustCompile(`(?i)\bGoogle\b`)},
	}
	pools := map[string]map[string]bool{}
	for _, v := range vendors {
		pools[v.key] = map[string]bool{}
	}
	hex6 := regexp.MustCompile(`^[0-9A-Fa-f]{6}$`)

	resp, err := http.Get(source)
	if err != nil {
		fatal(err)
	}
	defer resp.Body.Close()
	r := csv.NewReader(resp.Body)
	r.FieldsPerRecord = -1
	for {
		row, err := r.Read()
		if err != nil {
			break
		}
		if len(row) < 3 || row[0] != "MA-L" {
			continue
		}
		asn := strings.ToLower(strings.TrimSpace(row[1]))
		if !hex6.MatchString(asn) {
			continue
		}
		first, _ := strconv.ParseUint(asn[0:2], 16, 8)
		if first&0x03 != 0 { // skip locally-administered / multicast
			continue
		}
		for _, v := range vendors {
			if v.re.MatchString(row[2]) {
				pools[v.key][asn] = true
				break
			}
		}
	}

	out, err := os.Create("oui_data.go")
	if err != nil {
		fatal(err)
	}
	defer out.Close()
	w := bufio.NewWriter(out)
	defer w.Flush()
	fmt.Fprint(w, "// Code generated by internal/netcfg/gen/gen_ouis.go; DO NOT EDIT.\n")
	fmt.Fprintf(w, "// Source: IEEE MA-L registry (%s).\n", source)
	fmt.Fprint(w, "// Only globally-administered unicast prefixes (real hardware) are kept.\n\n")
	fmt.Fprint(w, "package netcfg\n\n")
	fmt.Fprint(w, "// Each constant is a run of 3-byte OUI prefixes, hex, decoded at init.\n")
	for _, v := range vendors {
		keys := make([]string, 0, len(pools[v.key]))
		for k := range pools[v.key] {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		fmt.Fprintf(w, "// %s: %d OUIs\n", v.key, len(keys))
		fmt.Fprintf(w, "const %sOUIHex = \"\" +\n", v.key)
		joined := strings.Join(keys, "")
		for i := 0; i < len(joined); i += 96 {
			end := i + 96
			if end > len(joined) {
				end = len(joined)
			}
			fmt.Fprintf(w, "\t%q +\n", joined[i:end])
		}
		fmt.Fprint(w, "\t\"\"\n\n")
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
